# Usage: python3 -I tools/gen_opcodes.py path/to/aco_opcodes.py > src/opcodes.rs
# ACO's "gfx10" column mixes GFX10.1 and 10.3; the tables below fix it for gfx1013.
import runpy
import sys

ns = runpy.run_path(sys.argv[1])
FMT = {
    "SOP1": "Sop1", "SOP2": "Sop2", "SOPK": "Sopk", "SOPP": "Sopp", "SOPC": "Sopc",
    "SMEM": "Smem", "DS": "Ds", "MTBUF": "Mtbuf", "MUBUF": "Mubuf", "MIMG": "Mimg",
    "EXP": "Exp", "FLAT": "Flat", "GLOBAL": "Global", "SCRATCH": "Scratch",
    "VINTRP": "Vintrp", "VOP1": "Vop1", "VOP2": "Vop2", "VOPC": "Vopc", "VOP3": "Vop3",
    "VOP3P": "Vop3p",
}

DROP = {
    "v_fmac_legacy_f32", "v_fma_legacy_f32", "v_interp_p2_hi_f16",
    "buffer_atomic_csub", "global_atomic_csub",
    "v_dot2c_f32_f16", "v_dot4c_i32_i8", "v_dot2_i32_i16", "v_dot2_u32_u16", "v_dot4_i32_i8",
    "v_dot4_u32_u8", "v_dot8_i32_i4", "v_dot8_u32_u4", "v_dot2_f32_f16",
    "s_mov_fed_b32", "global_load_dword_addtid", "global_store_dword_addtid",
}

RENAME = {
    "v_add_u32": "v_add_nc_u32", "v_sub_u32": "v_sub_nc_u32", "v_subrev_u32": "v_subrev_nc_u32",
    "v_addc_co_u32": "v_add_co_ci_u32", "v_subb_co_u32": "v_sub_co_ci_u32",
    "v_subbrev_co_u32": "v_subrev_co_ci_u32",
    "v_add_i32": "v_add_nc_i32", "v_sub_i32": "v_sub_nc_i32",
    "v_add_i16": "v_add_nc_i16", "v_sub_i16": "v_sub_nc_i16",
    "v_add_u16_e64": "v_add_nc_u16", "v_sub_u16_e64": "v_sub_nc_u16",
}

# name: (format, opcode, defs, srcs) for instructions ACO lacks on GFX10.
EXTRA = {
    "v_illegal": ("Vop2", 0x0, [], []),
    "image_gather4h": ("Mimg", 0x61, [], []),
    "image_sample_cd_g16": ("Mimg", 0xe8, [], []),
    "image_sample_cd_cl_g16": ("Mimg", 0xe9, [], []),
    "image_sample_c_cd_g16": ("Mimg", 0xea, [], []),
    "image_sample_c_cd_cl_g16": ("Mimg", 0xeb, [], []),
    "image_sample_cd_o_g16": ("Mimg", 0xec, [], []),
    "image_sample_cd_cl_o_g16": ("Mimg", 0xed, [], []),
    "image_sample_c_cd_o_g16": ("Mimg", 0xee, [], []),
    "image_sample_c_cd_cl_o_g16": ("Mimg", 0xef, [], []),
}

# Opcode numbers LLVM's gfx1013 encodes differently from ACO's gfx10 column.
CODE_FIX = {
    "s_ttracedata_imm": 0x28,
}

# Operand types LLVM sees differently from ACO.
SRC_FIX = {
    "v_alignbit_b32": ["U32", "U32", "U32"],
    "v_alignbyte_b32": ["U32", "U32", "U32"],
}

TY = {
    ("l", 1, 1): "Lane", ("u", 16, 1): "U16", ("u", 32, 1): "U32", ("u", 64, 1): "U64",
    ("u", 32, 4): "U128", ("i", 64, 1): "I64", ("f", 16, 1): "F16", ("f", 32, 1): "F32",
    ("f", 64, 1): "F64", ("u", 16, 2): "PkU16", ("f", 16, 2): "PkF16",
}
KIND = {0: "n", 1: "l", 2: "u", 3: "i", 4: "f", 5: "b"}
FIXED = {1: "Exec", 2: "Scc", 3: "M0", 4: "Imm"}


def ty(t):
    if int(t.fixed_reg) in FIXED:
        if int(t.fixed_reg) == 1 and t.bit_size == 1:
            return "Exec"
        if int(t.fixed_reg) == 1:
            return "U64" if t.bit_size == 64 else "U32"
        return FIXED[int(t.fixed_reg)]
    return TY[(KIND[int(t.base_type)], t.bit_size, t.num_components)]


rows = []
for name, ins in ns["instructions"].items():
    if ins.op.gfx10 < 0 or ins.format.name not in FMT or name in DROP:
        continue
    name = RENAME.get(name, name)
    if name.startswith("v_cmp") and name.rsplit("_", 1)[1][0] in "iu":
        name = name.replace("_lg_", "_ne_").replace("_tru_", "_t_")
    if name.endswith("_e64"):
        name = name[:-4]
    rows.append((FMT[ins.format.name], ins.op.gfx10, name,
                 [ty(d) for d in ins.definitions], [ty(s) for s in ins.operands]))
rows = [(f, CODE_FIX.get(n, c), n, d, SRC_FIX.get(n, s)) for f, c, n, d, s in rows]
for name, (fmt, code, defs, srcs) in EXTRA.items():
    rows.append((fmt, code, name, defs, srcs))
rows.sort(key=lambda r: (list(FMT.values()).index(r[0]), r[1]))

print("// @generated by tools/gen_opcodes.py from Mesa's src/amd/compiler/aco_opcodes.py.")
print("// Copyright (c) 2018 Valve Corporation, SPDX-License-Identifier: MIT")
print("// Edited by the generator for gfx1013 and LLVM's mnemonics.")
print()
print("use crate::opinfo::{Fmt::*, OpInfo, Ty::*};")
print()
print("pub(crate) static OPS: &[OpInfo] = &[")
for fmt, code, name, defs, srcs in rows:
    print('    OpInfo { fmt: %s, code: 0x%x, name: "%s", defs: &[%s], srcs: &[%s] },'
          % (fmt, code, name, ", ".join(defs), ", ".join(srcs)))
print("];")
