#!/usr/bin/env python3
"""Writes src/suite/formats.rs: the GFX10 image formats the image tests sweep,
from Mesa's src/amd/registers/gfx10-rsrc.json (MIT).

usage: gen_formats.py MESA_CHECKOUT > src/suite/formats.rs
"""
import json
import re
import sys

KINDS = ["UNORM", "SNORM", "USCALED", "SSCALED", "UINT", "SINT", "FLOAT", "SRGB", "UFLOAT", "SFLOAT"]
SKIP = re.compile(r"^(INVALID|FMASK|MM_|YCBCR|GB_GR|BG_RG|1_|1_REVERSED)")


def bits(name):
    if name.startswith("BC"):
        n = int(name[2])
        return 64 if n in (1, 4) else 128
    parts = name.split("_")
    total = 0
    for p in parts:
        if p in KINDS or p == "CLAMP":
            break
        if p == "6E4":
            total += 8
        elif p == "7E3":
            total += 10
        elif p == "X24":
            total += 24
        elif p.isdigit():
            total += int(p)
        else:
            return None
    return total


def main():
    path = sys.argv[1] + "/src/amd/registers/gfx10-rsrc.json"
    entries = json.load(open(path))["enums"]["GFX10_FORMAT"]["entries"]
    print("// @generated by tools/gen_formats.py from Mesa's src/amd/registers/gfx10-rsrc.json.")
    print("// Copyright (c) Advanced Micro Devices, Inc. and Mesa contributors, SPDX-License-Identifier: MIT")
    print()
    print("/// A GFX10 image format: its name, FORMAT number, bits per texel (per 4x4")
    print("/// block for BC formats) and channel type.")
    print("pub type Format = (&'static str, u32, u32, &'static str);")
    print()
    rows = []
    for e in entries:
        name = e["name"].replace("GFX10_FORMAT_", "").strip()
        if SKIP.match(name):
            continue
        b = bits(name)
        if b is None:
            continue
        kind = next((k for k in KINDS if name.endswith(k)), "OTHER")
        rows.append((name, e["value"], b, kind))
    print(f"pub const FORMATS: [Format; {len(rows)}] = [")
    for r in rows:
        print(f'    ("{r[0]}", {r[1]}, {r[2]}, "{r[3]}"),')
    print("];")


main()
