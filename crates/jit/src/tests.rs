#[test]
fn a_kick_at_an_exception_vector_reports_the_exception() {
    let _vm = VM.lock().unwrap_or_else(|e| e.into_inner());
    let mem = guest();
    let mut m = machine().unwrap();
    m.sync(&mem).unwrap();
    let pc = m.load_code(0x1000, &increment());
    let at = (pc - layout::RUNTIME_VA) as usize;
    let mut cpu = Cpu::new(&mut m).unwrap().unwrap();
    let root = SHARED.roots[SHARED.active.load(Ordering::SeqCst)].load(Ordering::SeqCst);

    // A kick made before entering lands before the first instruction.
    cpu.vcpu.kicker().kick();
    let exit = cpu.enter(root, at, None, 0).unwrap();
    assert!(
        matches!(exit, Exit::Canceled { pc: p, .. } if p == pc),
        "{exit:?}"
    );

    // A vCPU kicked while at the synchronous vector, after taking a fault
    // in translated code but before the vector's hvc, reports that fault.
    let (esr, far, elr) = (0x9600_0007, 0x60_0000, pc);
    cpu.vcpu.set_sys_reg(sysreg::ESR_EL1, esr).unwrap();
    cpu.vcpu.set_sys_reg(sysreg::FAR_EL1, far).unwrap();
    cpu.vcpu.set_sys_reg(sysreg::ELR_EL1, elr).unwrap();
    cpu.vcpu.kicker().kick();
    let exit = cpu.enter(root, layout::VECTORS + 0x200, None, 0).unwrap();
    assert_eq!(exit, Exit::Fault { esr, far, elr });
    cpu.release(&mut m);
}

/// Maps a page in each of `count` separate 2 MiB blocks from `base`, so each
/// needs a level-3 table of its own.
fn scattered_pages(mem: &Memory, base: u64, count: u64) {
    for k in 0..count {
        mem.map(base + (k << 21), PAGE_SIZE, Prot::RW, "scattered")
            .unwrap();
    }
}

#[test]
fn a_map_as_fragmented_as_gta_v_reaches_the_vm() {
    let _vm = VM.lock().unwrap_or_else(|e| e.into_inner());
    const BASE: u64 = 0x10_0000_0000;
    let mem = guest();
    scattered_pages(&mem, BASE, 1500);
    let mut m = machine().unwrap();
    assert!(m.sync(&mem).unwrap());
    // Added in place to the tables vCPUs use, then a full rebuild.
    scattered_pages(&mem, BASE + (1500 << 21), 1500);
    assert!(m.sync(&mem).unwrap());
    let last = BASE + (2999 << 21);
    mem.protect(BASE, Prot::READ).unwrap();
    assert!(m.sync(&mem).unwrap());
    let pc = m.load_code(0x1000, &increment());
    let mut cpu = Cpu::new(&mut m).unwrap().unwrap();
    cpu.set_reg(0, last).unwrap();
    assert_eq!(cpu.run(&m, pc).unwrap(), Exit::Hvc(7));
    assert_eq!(mem.read_u64(last).unwrap(), 1);
    cpu.release(&mut m);
}

/// `mov ebx, CODE + 0xf80` (scratch memory) and `mov r14d, CODE + 0x800`
/// (where `record` stores results).
fn scratch_and_results() -> Vec<u8> {
    let mut code = vec![0xbb];
    code.extend_from_slice(&(CODE as u32 + 0xf80).to_le_bytes());
    code.extend_from_slice(&[0x41, 0xbe]);
    code.extend_from_slice(&(CODE as u32 + 0x800).to_le_bytes());
    code
}

/// `push imm32; popfq`.
fn set_rflags(code: &mut Vec<u8>, rflags: u32) {
    code.push(0x68);
    code.extend_from_slice(&rflags.to_le_bytes());
    code.push(0x9d);
}

/// Stores RAX and RFLAGS at r14 and advances it.
fn record(code: &mut Vec<u8>) {
    code.extend_from_slice(&[
        0x9c, // pushfq
        0x5a, // pop rdx
        0x49, 0x89, 0x06, // mov [r14], rax
        0x49, 0x89, 0x56, 0x08, // mov [r14 + 8], rdx
        0x49, 0x83, 0xc6, 0x10, // add r14, 16
    ]);
}

/// RFLAGS values to start from: none, all, only CF and OF, all but CF and OF.
const FLAGS_IN: [u32; 4] = [0x002, 0x8d7, 0x803, 0x0d6];

const ADX_FORMS: &[&[u8]] = &[
    &[0x66, 0x48, 0x0f, 0x38, 0xf6, 0xc1], // adcx rax, rcx
    &[0x66, 0x0f, 0x38, 0xf6, 0xc1],       // adcx eax, ecx
    &[0xf3, 0x48, 0x0f, 0x38, 0xf6, 0xc1], // adox rax, rcx
    &[0xf3, 0x0f, 0x38, 0xf6, 0xc1],       // adox eax, ecx
    &[0x66, 0x48, 0x0f, 0x38, 0xf6, 0x03], // adcx rax, [rbx]
    &[0xf3, 0x0f, 0x38, 0xf6, 0x43, 0x08], // adox eax, [rbx + 8]
];

#[test]
fn adcx_and_adox_change_only_their_own_flag_like_the_interpreter() {
    assert_all_translated(&ADX_FORMS.concat());
    let pairs = [
        (u64::MAX, 0u64),
        (0x1234_5678_8000_0000, 0x8765_4321_8000_0000),
        (0x8000_0000_0000_0001, 0xffff_ffff_ffff_fffe),
    ];
    for rflags in FLAGS_IN {
        let mut code = scratch_and_results();
        for (a, b) in pairs {
            for op in ADX_FORMS {
                code.extend_from_slice(&[0x48, 0xb8]);
                code.extend_from_slice(&a.to_le_bytes());
                code.extend_from_slice(&[0x48, 0xb9]);
                code.extend_from_slice(&b.to_le_bytes());
                // mov [rbx], rcx; mov [rbx + 8], rcx
                code.extend_from_slice(&[0x48, 0x89, 0x0b, 0x48, 0x89, 0x4b, 0x08]);
                set_rflags(&mut code, rflags);
                code.extend_from_slice(op);
                record(&mut code);
            }
        }
        code.extend_from_slice(&[0xff, 0xd5]); // call rbp
        assert!(code.len() <= 0x800);
        same_as_interpreter(&code, &[]);
    }
}

