/// Lanes that compare equal, less, greater and unordered (NaN on either side).
fn compare_data() -> Vec<u8> {
    let mut data = vec![0u8; 0x80];
    let nan = f32::from_bits(0x7fc0_0001);
    let singles = [
        1.0f32, nan, 2.0, -0.0, 5.0, -1.0, nan, 3.0, 1.0, 1.0, 3.0, 0.0, 4.0, nan, nan, -3.0,
    ];
    for (k, v) in singles.iter().enumerate() {
        data[4 * k..][..4].copy_from_slice(&v.to_le_bytes());
    }
    let doubles = [1.0f64, f64::NAN, 1.0, -2.0, 0.0, -0.0];
    for (k, v) in doubles.iter().enumerate() {
        data[0x40 + 8 * k..][..8].copy_from_slice(&v.to_le_bytes());
    }
    data[0x70..0x78].copy_from_slice(&0x8000_0001_7fff_ffffu64.to_le_bytes());
    data
}

